    this.traitEn,
    this.abilityDe,
    this.abilityEn,
    this.storyDe,
    this.storyEn,
  );
  final CharacterGroup group;
  final String traitDe, traitEn, abilityDe, abilityEn, storyDe, storyEn;
}

