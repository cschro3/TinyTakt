  dinos('Dino-Abenteurer', 'Dino adventurers'),
  explorers('Waldentdecker', 'Forest explorers'),
  dragons('Drachen & Spukfreunde', 'Dragons & spooky friends'),
  sea('Meeresabenteurer', 'Sea adventurers'),
  robots('Roboter & Maschinen', 'Robots & machines'),
  fantasy('Fantasiewesen', 'Fantasy creatures'),
  inventors('Kleine Erfinder', 'Little inventors'),
  farm('Hofhelden', 'Farm heroes'),
  jungle('Dschungelmutige', 'Jungle brave ones');

  const CharacterGroup(this.de, this.en);
  final String de, en;
}

